import type { TermMatchMode } from './ruleEngine.js';

/**
 * بصمة محتوى البذور (fingerprint) بدل رقم إصدار يدوي.
 *
 * العلة: رقم الإصدار اليدوي يتخلّف عن الواقع (نُسي ترقيمه عند تعديل مصطلح)، فيبقى المستخدم القائم
 * على معجم قديم. البصمة تُحسب من محتوى البذور نفسه، فأي إضافة/تصحيح مصطلح يغيّرها تلقائياً
 * ⇒ يُعاد فحص إعدادات المستخدم وتُضاف الناقصات فقط.
 *
 * ملاحظة: القيمة **ليست ترتيبية**؛ المقارنة تتم بالتساوي (`!==`) لا بأصغر/أكبر.
 */
let cachedFingerprint: number | null = null;

/** FNV-1a (32-bit) على تمثيل قانوني حتمي للبذور. */
function fingerprint(text: string): number {
  let hash = 0x811c9dc5;
  for (let index = 0; index < text.length; index += 1) {
    hash ^= text.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  // نطاق موجب داخل integer (int4) مع تجنّب الصفر.
  return (hash % 2_000_000_000) + 1;
}

/** تُحسب مرة واحدة بعد تعريف كل البذور (انظر نهاية الملف). */
export function seedFingerprint(): number {
  if (cachedFingerprint !== null) return cachedFingerprint;
  cachedFingerprint = fingerprint(
    JSON.stringify({
      dictionaries: SEED_DICTIONARIES,
      filters: SEED_FILTERS,
      classifications: SEED_CLASSIFICATIONS,
      templates: SEED_TEMPLATES,
      bindings: SEED_TEMPLATE_BINDINGS,
      removals: SEED_TERM_REMOVALS,
    }),
  );
  return cachedFingerprint;
}

export interface SeedTerm {
  term: string;
  mode?: TermMatchMode;
  loose?: boolean;
}

export interface SeedDictionary {
  name: string;
  kind: 'keywords' | 'synonyms' | 'request_patterns' | 'exclusions' | 'vocabulary';
  terms: SeedTerm[];
}

export interface SeedCondition {
  mode: 'all' | 'any';
  negate?: boolean;
  minMatches?: number;
  /** مصطلحات حرفية في الشرط. */
  terms?: SeedTerm[];
  /** قاموس كامل يُضاف إلى مصطلحات الشرط (بالإضافة إلى `terms` إن وُجدت). */
  dictionary?: string;
}

export interface SeedFilter {
  name: string;
  description: string;
  priority: number;
  conditions: SeedCondition[];
}

/**
 * يحوّل قائمة مصطلحات نصية إلى مصطلحات بذور:
 * - العبارة (فيها فراغ) ⇒ مطابقة `phrase`.
 * - غير ذلك ⇒ مطابقة كلمة كاملة (السلوك الافتراضي في المحرّك).
 */
function terms(...values: string[]): SeedTerm[] {
  return values.map((term) => (term.includes(' ') ? { term, mode: 'phrase' as TermMatchMode } : { term }));
}

