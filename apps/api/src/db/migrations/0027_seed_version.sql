-- نسخة البذور لكل مستخدم: تسمح بتوسيع المعجم لاحقاً دون المساس بتعديلات المستخدم.
--
-- المشكلة التي تُحلّ: البذور كانت تُطبَّق مرة واحدة (`seeded_at`)، فأي توسعة معجمية بعد ذلك
-- لا تصل إلى المستخدمين القدامى أبداً — فيبقى النظام «فارغاً» على حدّ تعبير المستخدم.
--
-- الحل: `seed_version` يبدأ من 1 للمستخدمين الموجودين (بذروا بالنسخة الأولى)، فيرفعه التطبيق
-- إلى `SEED_VERSION` عند أول تحميل إعدادات، ويضيف **الناقص فقط**: مصطلحات جديدة، قواميس جديدة،
-- قوالب جديدة، وربط تصنيف↔قالب إن لم يكن موجوداً. لا يحذف شرطاً ولا يعدّل قاعدة عدّلها المستخدم.

alter table user_config_state
  add column if not exists seed_version integer not null default 1;

comment on column user_config_state.seed_version is
  'آخر نسخة بذور طُبِّقت لهذا المستخدم؛ يرفعها التطبيق إلى SEED_VERSION بإضافة الناقص فقط.';
