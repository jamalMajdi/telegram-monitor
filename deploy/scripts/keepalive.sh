#!/bin/sh
# نبضة استخدام يومية (Oracle Cloud Always Free).
#
# لماذا: سياسة أوراكل تعيد ملكية آلة Always Free إذا بقي **المئين 95** لوحدة المعالجة
# والشبكة والذاكرة تحت 20% لمدة 7 أيام. تطبيقنا خفيف بطبيعته (رسائل نصية كل دقيقة)،
# فقد يقع في هذا التصنيف بلا أي عطل حقيقي. نبضة قصيرة يومياً تُبعد الآلة عن «الخمول».
# التكلفة: ثانية واحدة من CPU يومياً. لا تمسّ البيانات ولا الخدمات.
set -eu

echo "[keepalive] $(date -u +%FT%TZ) نبضة بدأت"
# حمل حسابي قصير على نواة واحدة، بأدنى أولوية، بلا كتابة على القرص.
timeout 45 nice -n 19 sh -c 'i=0; while [ $i -lt 400000 ]; do i=$((i+1)); done; echo 1 > /dev/null | sha256sum >/dev/null' || true
echo "[keepalive] تمّت"
